"""SQLAlchemy models for the Bedrock Activity Dashboard."""

import uuid
from datetime import datetime, timezone

from sqlalchemy import (
    Boolean,
    Column,
    Date,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    JSON,
    Numeric,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import relationship

from app.database import Base


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class Team(Base):
    __tablename__ = "teams"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    name = Column(String(255), unique=True, nullable=False)
    description = Column(Text, nullable=True)
    created_at = Column(DateTime(timezone=True), default=utcnow, nullable=False)
    updated_at = Column(DateTime(timezone=True), default=utcnow, onupdate=utcnow, nullable=False)

    memberships = relationship("TeamMembership", back_populates="team", cascade="all, delete-orphan")


class TeamMembership(Base):
    __tablename__ = "team_memberships"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    team_id = Column(UUID(as_uuid=True), ForeignKey("teams.id", ondelete="CASCADE"), nullable=False)
    user_identity = Column(String(512), nullable=False)
    created_at = Column(DateTime(timezone=True), default=utcnow, nullable=False)

    team = relationship("Team", back_populates="memberships")

    __table_args__ = (
        UniqueConstraint("team_id", "user_identity", name="uq_team_user"),
    )


class ModelPricing(Base):
    __tablename__ = "model_pricing"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    model_id = Column(String(512), unique=True, nullable=False)
    input_token_price = Column(Numeric(20, 10), nullable=False)
    output_token_price = Column(Numeric(20, 10), nullable=False)
    cache_read_token_price = Column(Numeric(20, 10), nullable=False, default=0)
    cache_write_token_price = Column(Numeric(20, 10), nullable=False, default=0)
    is_default = Column(Boolean, default=False, nullable=False)
    created_at = Column(DateTime(timezone=True), default=utcnow, nullable=False)
    updated_at = Column(DateTime(timezone=True), default=utcnow, onupdate=utcnow, nullable=False)


class SummaryReport(Base):
    __tablename__ = "summary_reports"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    period_start = Column(DateTime(timezone=True), nullable=False)
    period_end = Column(DateTime(timezone=True), nullable=False)
    report_type = Column(String(50), nullable=False)  # "daily", "weekly"
    content = Column(JSON, nullable=False)
    created_at = Column(DateTime(timezone=True), default=utcnow, nullable=False)


class ChatMessage(Base):
    __tablename__ = "chat_messages"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    session_id = Column(UUID(as_uuid=True), nullable=False, index=True)
    role = Column(String(50), nullable=False)  # "user" or "assistant"
    content = Column(Text, nullable=False)
    created_at = Column(DateTime(timezone=True), default=utcnow, nullable=False)
    # Authenticated caller identity (Cognito email/username), captured on the
    # "user" row of each turn so Agent Chat activity attributes to the real
    # user instead of the "agent-chat"/"Agent Chat User" placeholder. Nullable
    # for rows written before this column existed and for the assistant row
    # (identity is only meaningful for who asked, not who answered).
    user_identity = Column(String(512), nullable=True)
    user_name = Column(String(255), nullable=True)


class DemoActivityRecord(Base):
    """Persisted, on-demand demo activity record.

    Generated by an admin via the Demo Data feature (not injected at request
    time). Mirrors the activity-record shape the analytics pipeline consumes,
    plus demo metadata (PII types embedded, whether it was a real Bedrock
    invocation, and the batch it was generated in). The primary key ``id`` is
    the synthetic record id so the row is also the activity record's id.
    """

    __tablename__ = "demo_activity_records"

    id = Column(String(255), primary_key=True)
    timestamp = Column(String(64), nullable=False)  # ISO-8601 string
    user_identity = Column(String(512), nullable=False)
    user_name = Column(String(255), nullable=False)
    model_id = Column(String(512), nullable=False)
    source_application = Column(String(255), nullable=True)
    source_ip = Column(String(64), nullable=True)
    input_tokens = Column(Integer, nullable=False, default=0)
    output_tokens = Column(Integer, nullable=False, default=0)
    cache_read_tokens = Column(Integer, nullable=False, default=0)
    cache_write_tokens = Column(Integer, nullable=False, default=0)
    prompt_text = Column(Text, nullable=True)
    response_text = Column(Text, nullable=True)
    # List of PII/sensitive types embedded in this record (e.g. ["ssn", "email"]).
    pii_types = Column(JSON, nullable=True)
    is_real_invocation = Column(Boolean, nullable=False, default=False)
    batch_id = Column(String(64), nullable=False, index=True)
    created_at = Column(DateTime(timezone=True), default=utcnow, nullable=False)
    # The ACTUAL time the underlying Bedrock call happened (as opposed to
    # ``timestamp``, which is a staged display value spread across the last
    # ~14 days so trend-oriented agents have a realistic pattern to analyze).
    # The real invocation independently shows up via CloudWatch/S3/CloudTrail
    # ingestion under the backend's own task-role identity; this column lets
    # that duplicate be matched and suppressed from the merged activity feed
    # (mirrors the existing Agent Chat placeholder-suppression pattern).
    # Nullable so older rows generated before this column existed degrade
    # gracefully (no suppression attempted for them).
    invoked_at = Column(DateTime(timezone=True), nullable=True)
    # Non-null only when this record's underlying Bedrock call was routed
    # through a tagged application inference profile (the "tagged
    # application spend" Demo Data option — see
    # demo_service.generate_demo_data(with_applications=True)). Lets
    # ProfileTagService resolve a real Application/Environment/Team
    # dimension for this record via the same path real CloudTrail/CloudWatch
    # records use, instead of it always landing in "unknown".
    inference_profile_arn = Column(String(1024), nullable=True)


class CurBilledCost(Base):
    """Authoritative billed cost rows (Tier A) ingested from the CUR 2.0 export.

    Coarse granularity: (IAM principal or Team tag) x day x model. Populated
    off-request by the CUR ingestion service via an idempotent upsert keyed on
    ``uq_cur_billed_key``, so re-ingesting a billing period replaces values
    rather than appending duplicate rows.
    """

    __tablename__ = "cur_billed_cost"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    billing_period = Column(String(7), nullable=False)  # YYYY-MM
    usage_date = Column(Date, nullable=False)  # day granularity
    iam_principal = Column(String(512), nullable=False)  # "" when absent
    team_tag = Column(String(255), nullable=False)  # activated Team tag; "" when absent
    resource_id = Column(String(1024), nullable=True)  # profile ARN when CUR carries it
    model_id = Column(String(512), nullable=False)  # normalized to bare form
    billed_cost = Column(Numeric(20, 10), nullable=False)  # summed unblended cost
    created_at = Column(DateTime(timezone=True), default=utcnow, nullable=False)
    updated_at = Column(DateTime(timezone=True), default=utcnow, onupdate=utcnow, nullable=False)

    __table_args__ = (
        UniqueConstraint(
            "billing_period",
            "usage_date",
            "iam_principal",
            "team_tag",
            "model_id",
            name="uq_cur_billed_key",
        ),
        Index("ix_cur_billed_usage_date", "usage_date"),
        Index("ix_cur_billed_principal", "iam_principal"),
    )


class InferenceProfileTag(Base):
    """Cache mapping an inference-profile ARN to its cost-allocation tags.

    Core dimensions (Application/Environment/Team) plus the extended taxonomy
    (AgentName/CostCenter/UseCase/Owner/Project) — see
    ``ProfileTagService``/``ProfileTags`` for resolution and
    ``docs/tag-taxonomy.md``-equivalent guidance in the FAQ tab. All extended
    columns are nullable/additive: absence never blocks resolution, it just
    renders as untagged for that dimension.
    """

    __tablename__ = "inference_profile_tag"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    profile_arn = Column(String(1024), unique=True, nullable=False)
    application = Column(String(255), nullable=True)
    environment = Column(String(64), nullable=True)  # prod/staging/sandbox/...
    team = Column(String(255), nullable=True)
    # Extended tag taxonomy (additive; all optional).
    agent_name = Column(String(255), nullable=True)  # individual agent identification
    cost_center = Column(String(255), nullable=True)  # financial reporting
    use_case = Column(String(255), nullable=True)  # business capability
    owner = Column(String(255), nullable=True)  # responsible team/person
    project = Column(String(255), nullable=True)  # initiative tracking
    department = Column(String(255), nullable=True)  # business-unit attribution (executive rollup L2)
    resolved_at = Column(DateTime(timezone=True), default=utcnow, nullable=False)
    source = Column(String(20), nullable=False)  # "cur" | "bedrock_api"

    __table_args__ = (
        UniqueConstraint("profile_arn", name="uq_profile_arn"),
    )


