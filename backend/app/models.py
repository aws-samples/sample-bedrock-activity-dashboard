class AttributionTargetConfig(Base):
    """Singleton governance config for the unattributed-spend target.

    Enforced as a single row at the service layer (fetch-or-create default 0.05).
    """

    __tablename__ = "attribution_target_config"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    unattributed_target = Column(Numeric(5, 4), nullable=False)  # e.g. 0.0500 for < 5%
    staleness_hours_override = Column(Integer, nullable=True)  # optional per-env override
