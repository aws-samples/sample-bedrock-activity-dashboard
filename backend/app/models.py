class AppRuntimeSetting(Base):
    """Admin-managed runtime toggles persisted as a simple key/value table.

    Lets operators flip behavior that must survive restarts and span every
    task without rebuilding/redeploying the container. Current keys:

    - ``prompt_history_enabled`` (``"true"`` / ``"false"``): when ``"false"``,
      Agent Chat does not persist user/assistant messages to the DB, and the
      /api/activity/prompts endpoints return an empty paginated page with a
      disclosure flag so the UI can render an explanation. Default
      ``"true"`` so existing behavior is preserved on a fresh deploy.

    New keys may be added without a schema change — reads tolerate missing
    rows by applying code-level defaults.
    """

    __tablename__ = "app_runtime_settings"

    key = Column(String(100), primary_key=True)
    value = Column(Text, nullable=False)
    updated_at = Column(
        DateTime(timezone=True), default=utcnow, onupdate=utcnow, nullable=False
    )
    updated_by = Column(String(512), nullable=True)


class CurIngestionState(Base):
    """Tracks the state of CUR ingestion runs (last run, coverage, status)."""

    __tablename__ = "cur_ingestion_state"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    last_run_at = Column(DateTime(timezone=True), nullable=True)
    covered_through = Column(Date, nullable=True)  # max usage_date ingested
    latest_billing_period = Column(String(7), nullable=True)  # YYYY-MM
    assembly_id = Column(String(255), nullable=True)  # billing-period marker
    status = Column(String(50), nullable=False)  # success | failed | running
    error_detail = Column(Text, nullable=True)  # truncated diagnostic
    updated_at = Column(DateTime(timezone=True), default=utcnow, onupdate=utcnow, nullable=False)
